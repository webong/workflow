#!/usr/bin/env php
<?php
/**
 * Bundle all WorkFlow core + native protocol PHP into a single file
 * for Manticore AOT compilation (no require() calls at runtime).
 *
 * Usage: php tools/bundle-native.php > mod/manticore/php/bundle.php
 */

declare(strict_types=1);

$root = __DIR__ . '/..';
$files = [];

// Collect all source files
$dirs = [
    "$root/src/Contracts",
    "$root/src/Enums",
    "$root/src/Services",
    "$root/src/ValueObjects",
    "$root/mod/native/php",
];
foreach ($dirs as $dir) {
    foreach (new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator($dir)) as $file) {
        if ($file->getExtension() === 'php') {
            $files[] = $file->getPathname();
        }
    }
}
sort($files);

$output = [];
$output[] = '<?php';
$output[] = 'declare(strict_types=1);';
$output[] = '';
$output[] = '/*';
$output[] = ' * Bundled WorkFlow native protocol + core for Manticore AOT compilation.';
$output[] = ' * Generated by tools/bundle-native.php — do not edit by hand.';
$output[] = ' */';
$output[] = '';

foreach ($files as $file) {
    // reference.php and main.php are interpreter-only ("never compiled into native artifacts")
    $basename = basename($file);
    if ($basename === 'reference.php' || $basename === 'main.php') {
        continue;
    }
    $rel = substr($file, strlen($root) + 1);
    $content = file_get_contents($file);
    // Strip opening PHP tag and declare directive
    $content = preg_replace('/^<\?php\s*/', '', $content);
    $content = preg_replace("/^declare\(strict_types=1\);\s*/m", '', $content);
    // Strip require_once / require calls (all code is bundled inline)
    $content = preg_replace("/^\s*require_once\s+.*?;\s*/m", '', $content);
    $content = preg_replace("/^\s*require\s+.*?;\s*/m", '', $content);
    $content = trim($content);
    if ($content === '') {
        continue;
    }
    $output[] = "/* === $rel === */";
    $output[] = $content;
    $output[] = '';
}

echo implode("\n", $output);

// Entry point logic: read JSON from stdin, dispatch, print response.
echo <<<'PHP'

/* === entry-point === */
$fp = fopen('php://stdin', 'r');
$request = $fp !== false ? fread($fp, 1048577) : '';
if ($fp !== false) {
    fclose($fp);
}
echo workflow_native_dispatch(is_string($request) ? $request : '').PHP_EOL;
PHP;
