<?php

declare(strict_types=1);

namespace Webong\WorkFlow\Tools;

use InvalidArgumentException;
use RuntimeException;

/**
 * Renders the language-neutral contract manifest to Node, Python, and Go.
 *
 * The generator is deliberately small: it understands only the type grammar
 * documented in tools/contracts.php and emits plain type declarations. It
 * never emits validation, execution, or transport code — clients call the
 * server and render the diagnostics it returns.
 */
final class ClientContractGenerator
{
    /**
     * @param array{
     *     enums: array<string, array{description?: string, cases: array<string, string>}>,
     *     types: array<string, array{description?: string, fields: list<array{name: string, type: string, optional?: bool, description?: string}>}>
     * } $manifest
     * @return array{ts: string, py: string, go: string}
     */
    public static function render(array $manifest): array
    {
        return [
            'ts' => self::renderTypeScript($manifest),
            'py' => self::renderPython($manifest),
            'go' => self::renderGo($manifest),
        ];
    }

    /**
     * Writes the three generated files beneath $root and returns their paths.
     *
     * @param array{enums: array<string, mixed>, types: array<string, mixed>} $manifest
     * @return array<string, string> Language => path.
     */
    public static function write(array $manifest, string $root): array
    {
        /** @var array{ts: string, py: string, go: string} $rendered */
        $rendered = self::render($manifest);
        $paths = [
            'ts' => $root.'/types/work-flow.d.ts',
            'py' => $root.'/types/work_flow.py',
            'go' => $root.'/types/work_flow.go',
        ];

        foreach ($paths as $language => $path) {
            if (file_put_contents($path, $rendered[$language]) === false) {
                throw new RuntimeException("Cannot write {$path}");
            }
        }

        return $paths;
    }

    /**
     * @param array{enums: array<string, mixed>, types: array<string, mixed>} $manifest
     */
    private static function renderTypeScript(array $manifest): string
    {
        $out = "// Generated by tools/generate-clients.php from tools/contracts.php.\n"
            ."// Do not edit manually. Run `composer types` after changing the manifest.\n\n";

        foreach (self::enums($manifest) as $name => $enum) {
            $description = self::tsDoc($enum['description'] ?? null);
            $values = array_map(static fn (string $value): string => "'".$value."'", array_keys($enum['cases']));
            $out .= $description.'export type '.$name.' = '.implode(' | ', $values).";\n\n";
        }

        foreach (self::types($manifest) as $name => $type) {
            $out .= self::tsDoc($type['description'] ?? null).'export interface '.$name." {\n";
            foreach ($type['fields'] as $field) {
                $field = self::field($field);
                if (($field['description'] ?? '') !== '') {
                    $out .= '    /** '.str_replace('*/', '*\\/', (string) $field['description'])." */\n";
                }
                $optional = $field['optional'] ? '?' : '';
                $out .= '    '.$field['name'].$optional.': '.self::ts($field['type']).";\n";
            }
            $out .= "}\n\n";
        }

        return rtrim($out)."\n";
    }

    /**
     * @param array{enums: array<string, mixed>, types: array<string, mixed>} $manifest
     */
    private static function renderPython(array $manifest): string
    {
        $out = "# Generated by tools/generate-clients.php from tools/contracts.php.\n"
            ."# Do not edit manually. Run `composer types` after changing the manifest.\n"
            ."# Requires Python 3.11+ (typing.NotRequired).\n\n"
            ."from __future__ import annotations\n\n"
            ."from typing import Any, Literal, NotRequired, TypedDict\n\n";

        foreach (self::enums($manifest) as $name => $enum) {
            $values = array_map(static fn (string $value): string => "'".self::pyString($value)."'", array_keys($enum['cases']));
            $out .= self::pyDoc($enum['description'] ?? null);
            $out .= $name.' = Literal['.implode(', ', $values)."]\n\n";
        }

        foreach (self::types($manifest) as $name => $type) {
            $out .= self::pyDoc($type['description'] ?? null);
            $out .= 'class '.$name."(TypedDict):\n";
            if ($type['fields'] === []) {
                $out .= "    pass\n\n";
                continue;
            }
            foreach ($type['fields'] as $field) {
                $field = self::field($field);
                $out .= self::indent($field['description'] ?? null, '    ', '# ');
                $rendered = self::py($field['type']);
                if ($field['optional']) {
                    $rendered = 'NotRequired['.$rendered.']';
                }
                $out .= '    '.$field['name'].': '.$rendered."\n";
            }
            $out .= "\n";
        }

        return rtrim($out)."\n";
    }

    /**
     * @param array{enums: array<string, mixed>, types: array<string, mixed>} $manifest
     */
    private static function renderGo(array $manifest): string
    {
        $out = "// Code generated by tools/generate-clients.php from tools/contracts.php. DO NOT EDIT.\n\n"
            ."package workflow\n\n";

        if (self::goNeedsJson($manifest)) {
            $out .= "import \"encoding/json\"\n\n";
        }

        foreach (self::enums($manifest) as $name => $enum) {
            $out .= self::goDoc($enum['description'] ?? null);
            $out .= 'type '.$name." string\n\nconst (\n";
            $identifiers = array_map(
                static fn (string $case): string => $name.self::goCase($case),
                array_values($enum['cases']),
            );
            $width = $identifiers === [] ? 0 : max(array_map(strlen(...), $identifiers));
            $position = 0;
            foreach ($enum['cases'] as $value => $case) {
                $identifier = $identifiers[$position++];
                $out .= "\t".$identifier.str_repeat(' ', $width - strlen($identifier) + 1)
                    .$name.' = "'.self::goString($value)."\"\n";
            }
            $out .= ")\n\n";
        }

        foreach (self::types($manifest) as $name => $type) {
            $out .= self::goDoc($type['description'] ?? null);
            $out .= 'type '.$name." struct {\n";
            foreach ($type['fields'] as $field) {
                $field = self::field($field);
                $out .= self::indent($field['description'] ?? null, '	', '// ');
                $tag = $field['name'].($field['optional'] ? ',omitempty' : '');
                $out .= '	'.self::goName($field['name']).' '.self::go($field['type'], $field['optional']).' `json:"'.$tag.'"`'."\n";
            }
            $out .= "}\n\n";
        }

        return rtrim($out)."\n";
    }

    /**
     * @param array{enums: array<string, mixed>, types: array<string, mixed>} $manifest
     * @return array<string, array{description?: string, cases: array<string, string>}>
     */
    private static function enums(array $manifest): array
    {
        /** @var array<string, array{description?: string, cases: array<string, string>}> $enums */
        $enums = $manifest['enums'];

        return $enums;
    }

    /**
     * @param array{enums: array<string, mixed>, types: array<string, mixed>} $manifest
     * @return array<string, array{description?: string, fields: list<array{name: string, type: string, optional?: bool, description?: string}>}>
     */
    private static function types(array $manifest): array
    {
        /** @var array<string, array{description?: string, fields: list<array{name: string, type: string, optional?: bool, description?: string}>}> $types */
        $types = $manifest['types'];

        return $types;
    }

    /**
     * @param array{name: string, type: string, optional?: bool, description?: string} $field
     * @return array{name: string, type: string, optional: bool, description?: string}
     */
    private static function field(array $field): array
    {
        return [
            'name' => $field['name'],
            'type' => $field['type'],
            'optional' => $field['optional'] ?? false,
            'description' => $field['description'] ?? null,
        ];
    }

    /** TypeScript rendering. */
    private static function ts(string $type): string
    {
        $parts = self::split($type, '|');
        if (count($parts) > 1) {
            return implode(' | ', array_map(self::ts(...), $parts));
        }

        $type = trim($type);
        if (str_ends_with($type, '[]')) {
            $inner = self::ts(substr($type, 0, -2));

            return str_contains($inner, '|') ? '('.$inner.')[]' : $inner.'[]';
        }
        if (preg_match('/^map<(.+)>$/s', $type, $match) === 1) {
            return 'Record<string, '.self::ts($match[1]).'>';
        }
        if (preg_match('/^union<(.+)>$/s', $type, $match) === 1) {
            return implode(' | ', array_map(self::ts(...), self::split($match[1], ',')));
        }

        return match ($type) {
            'int', 'float' => 'number',
            'bool' => 'boolean',
            'unknown', 'any', 'null' => $type === 'null' ? 'null' : 'unknown',
            default => self::scalar($type),
        };
    }

    /** Python rendering. */
    private static function py(string $type): string
    {
        $parts = self::split($type, '|');
        if (count($parts) > 1) {
            return implode(' | ', array_map(self::py(...), $parts));
        }

        $type = trim($type);
        if (str_ends_with($type, '[]')) {
            return 'list['.self::py(substr($type, 0, -2)).']';
        }
        if (preg_match('/^map<(.+)>$/s', $type, $match) === 1) {
            return 'dict[str, '.self::py($match[1]).']';
        }
        if (preg_match('/^union<(.+)>$/s', $type, $match) === 1) {
            return implode(' | ', array_map(self::py(...), self::split($match[1], ',')));
        }

        return match ($type) {
            'string' => 'str',
            'int' => 'int',
            'float' => 'float',
            'bool' => 'bool',
            'unknown', 'any' => 'Any',
            'null' => 'None',
            default => self::scalar($type),
        };
    }

    /**
     * Go rendering. `$optional` makes value types pointers so absence stays
     * distinguishable from a zero value.
     */
    private static function go(string $type, bool $optional = false): string
    {
        if ($optional && trim($type) === 'unknown') {
            return 'json.RawMessage';
        }

        $parts = self::split($type, '|');
        if (in_array('null', $parts, true)) {
            $members = array_values(array_filter($parts, static fn (string $part): bool => trim($part) !== 'null'));
            if (count($members) === 1) {
                $base = self::go($members[0]);
                if (self::nilable($base)) {
                    return $base;
                }

                return '*'.$base;
            }
        }
        if (count($parts) > 1) {
            // Go has no union types; the wire value stays an untyped value.
            return 'any';
        }

        $type = trim($type);
        if (str_ends_with($type, '[]')) {
            return '[]'.self::go(substr($type, 0, -2));
        }
        if (preg_match('/^map<(.+)>$/s', $type, $match) === 1) {
            return 'map[string]'.self::go($match[1]);
        }
        if (preg_match('/^union<(.+)>$/s', $type, $match) === 1) {
            return 'any';
        }

        $base = match ($type) {
            'string' => 'string',
            'int' => 'int',
            'float' => 'float64',
            'bool' => 'bool',
            'unknown', 'any', 'null' => 'any',
            default => self::scalar($type),
        };

        if ($optional && ! self::nilable($base)) {
            return '*'.$base;
        }

        return $base;
    }

    /** @param array{enums: array<string, mixed>, types: array<string, mixed>} $manifest */
    private static function goNeedsJson(array $manifest): bool
    {
        foreach (self::types($manifest) as $type) {
            foreach ($type['fields'] as $field) {
                $field = self::field($field);
                if ($field['optional'] && trim($field['type']) === 'unknown') {
                    return true;
                }
            }
        }

        return false;
    }

    private static function nilable(string $goType): bool
    {
        return str_starts_with($goType, '*')
            || str_starts_with($goType, '[]')
            || str_starts_with($goType, 'map[')
            || $goType === 'any';
    }

    private static function scalar(string $type): string
    {
        if (preg_match('/^[A-Za-z_][A-Za-z0-9_]*$/', $type) !== 1) {
            throw new InvalidArgumentException("Unsupported contract type '{$type}'.");
        }

        return $type;
    }

    /**
     * Splits on a top-level separator, ignoring separators inside <>.
     *
     * @return list<string>
     */
    private static function split(string $value, string $separator): array
    {
        $parts = [];
        $depth = 0;
        $current = '';
        $length = strlen($value);
        for ($i = 0; $i < $length; $i++) {
            $character = $value[$i];
            if ($character === '<') {
                $depth++;
            } elseif ($character === '>') {
                $depth--;
            } elseif ($character === $separator && $depth === 0) {
                $parts[] = trim($current);
                $current = '';
                continue;
            }
            $current .= $character;
        }
        $parts[] = trim($current);

        return $parts;
    }

    private static function goName(string $name): string
    {
        $initialisms = ['id' => 'ID', 'url' => 'URL', 'api' => 'API', 'http' => 'HTTP', 'json' => 'JSON', 'sql' => 'SQL'];
        $parts = [];
        foreach (explode('_', $name) as $part) {
            if ($part === '') {
                continue;
            }
            $parts[] = $initialisms[strtolower($part)] ?? ucfirst($part);
        }

        return implode('', $parts);
    }

    private static function goCase(string $case): string
    {
        $parts = [];
        foreach (explode('_', $case) as $part) {
            if ($part === '') {
                continue;
            }
            $parts[] = ucfirst(strtolower($part));
        }

        return implode('', $parts);
    }

    private static function tsDoc(?string $description): string
    {
        if ($description === null || $description === '') {
            return '';
        }

        return "/**\n * ".str_replace('*/', '*\\/', $description)."\n */\n";
    }

    private static function pyDoc(?string $description): string
    {
        if ($description === null || $description === '') {
            return '';
        }

        return '# '.$description."\n";
    }

    private static function goDoc(?string $description): string
    {
        if ($description === null || $description === '') {
            return '';
        }

        return '// '.$description."\n";
    }

    private static function indent(?string $description, string $indent, string $prefix = ''): string
    {
        if ($description === null || $description === '') {
            return '';
        }

        return $indent.$prefix.$description."\n";
    }

    private static function pyString(string $value): string
    {
        return str_replace(['\\', "'"], ['\\\\', "\\'"], $value);
    }

    private static function goString(string $value): string
    {
        return str_replace(['\\', '"'], ['\\\\', '\\"'], $value);
    }
}
